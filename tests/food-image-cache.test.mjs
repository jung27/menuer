import assert from 'node:assert/strict';
import { createFoodImageCache } from '../lib/food-image-cache.ts';
let now = 100;
Date.now = () => now;
let calls = 0;
const cache = createFoodImageCache(2, 1000);
const lookup = async () => { calls++; return 'https://example.com/food.jpg'; };
await Promise.all(Array.from({length: 10}, () => cache('rice', lookup)));
assert.equal(calls, 1, 'concurrent duplicate lookups share one request');
await cache('rice', lookup);
assert.equal(calls, 1);
now += 1001;
await cache('rice', lookup);
assert.equal(calls, 2, 'expired entries refresh');
await cache('noodle', lookup);
await cache('bread', lookup);
await cache('rice', lookup);
assert.equal(calls, 5, 'cache size is bounded');
await cache('failure', async () => undefined);
assert.equal(await cache('failure', lookup), 'https://example.com/food.jpg');
await assert.rejects(cache('error', async () => { throw Error('offline'); }));
assert.equal(await cache('error', lookup), 'https://example.com/food.jpg');
assert.equal(await cache('missing', async () => null), null);
assert.equal(await cache('missing', lookup), null);
console.log('PASS: public image cache reuse, concurrent deduplication, expiry, eviction and failure retry');
